"""OpenRouter models used in the experiment.

The model IDs and Single, worker, and judge roles below match the saved experiment
configuration. Explicit IDs avoid aliases such as ``latest``, but do not guarantee
unchanged provider deployments or behavior over time.
"""

import json
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator
import requests

from .settings import load_openrouter_config


MODELS = {
    "mistral": "mistralai/mistral-small-2603",
    "qwen": "qwen/qwen3.7-plus",
    "gemini": "google/gemini-2.5-pro",
    "openai": "openai/gpt-5-mini",
}

SINGLE_MODEL = "mistral"
LLMC_WORKER_MODELS = ("openai", "mistral", "gemini")
LLMC_JUDGE_MODEL = "qwen"

OPENROUTER_KEY_URL = "https://openrouter.ai/api/v1/key"
OPENROUTER_CHAT_URL = "https://openrouter.ai/api/v1/chat/completions"
REQUEST_TIMEOUT_SECONDS = 120


class ClassificationOutput(BaseModel):
    """Strict four-field output expected from every classification model."""

    model_config = ConfigDict(extra="forbid")

    ai_label: Literal["None", "Low", "Medium", "High"]
    confidence_score: int = Field(ge=0, le=100)
    ai_products_services: list[str] = Field(
        description="Customer-facing commercial AI products or services only"
    )
    supporting_evidence: list[str] = Field(
        description="Concise excerpts from the website supporting the classification"
    )

    @model_validator(mode="after")
    def validate_none_has_no_ai_evidence(self) -> "ClassificationOutput":
        if self.ai_label == "None" and (
            self.ai_products_services or self.supporting_evidence
        ):
            raise ValueError(
                "None classifications must have empty products and evidence lists"
            )
        return self


class ModelResult(BaseModel):
    """Validated classification plus request metadata generated by our code."""

    classification: ClassificationOutput
    cost: float = Field(ge=0)
    generation_id: str
    model: str


def classification_json_schema() -> dict[str, Any]:
    """Return the provider-portable schema for structured model output.

    Anthropic does not accept numeric bounds in its structured-output schema.
    Pydantic still enforces the 0-100 range after the response is returned.
    """

    schema = ClassificationOutput.model_json_schema()
    confidence_schema = schema["properties"]["confidence_score"]
    confidence_schema.pop("minimum", None)
    confidence_schema.pop("maximum", None)
    return schema


def check_openrouter_connection() -> dict[str, Any]:
    """Authenticate with OpenRouter without making a paid model request."""

    config = load_openrouter_config()
    response = requests.get(
        OPENROUTER_KEY_URL,
        headers={"Authorization": f"Bearer {config.api_key}"},
        timeout=REQUEST_TIMEOUT_SECONDS,
    )

    try:
        body = response.json()
    except requests.JSONDecodeError as error:
        raise RuntimeError(
            f"OpenRouter returned non-JSON HTTP {response.status_code}"
        ) from error

    if not response.ok:
        api_error = body.get("error", {})
        message = api_error.get("message", "Unknown OpenRouter error")
        provider_detail = api_error.get("metadata", {}).get("raw")
        if provider_detail:
            message = f"{message}: {provider_detail}"
        raise RuntimeError(f"OpenRouter HTTP {response.status_code}: {message}")

    return body["data"]


def classify_text(model_name: str, prompt: str) -> ModelResult:
    """Classify one website text prompt with one configured model."""

    if model_name not in MODELS:
        raise ValueError(
            f"Unknown model {model_name!r}; choose one of: {', '.join(MODELS)}"
        )

    config = load_openrouter_config()
    model_id = MODELS[model_name]
    response = requests.post(
        OPENROUTER_CHAT_URL,
        headers={
            "Authorization": f"Bearer {config.api_key}",
            "Content-Type": "application/json",
        },
        json={
            "model": model_id,
            "messages": [{"role": "user", "content": prompt}],
            "stream": False,
            "response_format": {
                "type": "json_schema",
                "json_schema": {
                    "name": "ai_involvement_classification",
                    "strict": True,
                    "schema": classification_json_schema(),
                },
            },
            "provider": {"require_parameters": True},
        },
        timeout=REQUEST_TIMEOUT_SECONDS,
    )

    try:
        body = response.json()
    except requests.JSONDecodeError as error:
        raise RuntimeError(
            f"OpenRouter returned non-JSON HTTP {response.status_code}"
        ) from error

    if not response.ok:
        api_error = body.get("error", {})
        message = api_error.get("message", "Unknown OpenRouter error")
        provider_detail = api_error.get("metadata", {}).get("raw")
        if provider_detail:
            message = f"{message}: {provider_detail}"
        raise RuntimeError(f"OpenRouter HTTP {response.status_code}: {message}")

    try:
        choice = body["choices"][0]
        content = choice["message"]["content"]
    except (KeyError, IndexError, TypeError) as error:
        finish_reason = None
        if isinstance(body.get("choices"), list) and body["choices"]:
            finish_reason = body["choices"][0].get("finish_reason")
        raise RuntimeError(
            f"OpenRouter response missing message content (finish_reason={finish_reason!r})"
        ) from error
    if not isinstance(content, str) or not content.strip():
        raise RuntimeError(
            "OpenRouter response contained empty message content "
            f"(finish_reason={choice.get('finish_reason')!r})"
        )
    try:
        classification = ClassificationOutput.model_validate(json.loads(content))
    except (TypeError, json.JSONDecodeError, ValueError) as error:
        raise RuntimeError(
            "OpenRouter returned message content that failed structured validation "
            f"(finish_reason={choice.get('finish_reason')!r})"
        ) from error
    try:
        cost = body["usage"]["cost"]
        generation_id = body["id"]
    except (KeyError, TypeError) as error:
        raise RuntimeError("OpenRouter response missing usage cost or generation ID") from error

    if isinstance(cost, bool) or not isinstance(cost, (int, float)):
        raise RuntimeError("OpenRouter response did not include a numeric usage cost")

    return ModelResult(
        classification=classification,
        cost=float(cost),
        generation_id=generation_id,
        model=model_id,
    )


def main() -> None:
    """Run the free OpenRouter authentication check."""

    try:
        key_info = check_openrouter_connection()
    except (ValueError, RuntimeError, requests.RequestException) as error:
        raise SystemExit(f"OpenRouter connection failed: {error}") from error

    print("OpenRouter connection successful.")
    if key_info.get("limit_remaining") is not None:
        print(f"Credit limit remaining: {key_info['limit_remaining']}")


if __name__ == "__main__":
    main()
